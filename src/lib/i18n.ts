/** BCP-47 tag for Intl / toLocaleString. */
export function dateLocale(locale: Locale): string {
  switch (locale) {
    case "en":
      return "en-US";
    case "ja":
      return "ja-JP";
    case "ko":
      return "ko-KR";
    case "zh-Hans":
      return "zh-CN";
    default:
      return "zh-HK";
  }
}

/** List join separator (aligned with mobile LanguageStore). */
export function listSeparator(locale: Locale): string {
  switch (locale) {
    case "en":
    case "ko":
      return ", ";
    case "ja":
      return "、";
    default:
      return "，";
  }
}

