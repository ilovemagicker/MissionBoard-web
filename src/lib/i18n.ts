export type MessageKey = keyof (typeof dict)["zh-Hant"];

export function t(locale: Locale, key: MessageKey): string {
  return dict[locale][key] ?? dict["zh-Hant"][key] ?? key;
}

export function parseLocale(value: string | undefined | null): Locale {
  return value === "en" ? "en" : "zh-Hant";
}

export function statusLabel(locale: Locale, status: string): string {
  if (status === "todo") return t(locale, "statusTodo");
  if (status === "inProgress") return t(locale, "statusInProgress");
  if (status === "done") return t(locale, "statusDone");
  return status;
}

export function roleLabel(locale: Locale, role: string): string {
  if (role === "owner") return t(locale, "roleOwner");
  if (role === "admin") return t(locale, "roleAdmin");
  if (role === "member") return t(locale, "roleMember");
  return role;
}

export function activityKindLabel(locale: Locale, kind: string): string {
  switch (kind) {
    case "mission_created":
      return t(locale, "kindMissionCreated");
    case "mission_status":
      return t(locale, "kindMissionStatus");
    case "step_done":
      return t(locale, "kindStepDone");
    case "step_claimed":
      return t(locale, "kindStepClaimed");
    case "step_claim_requested":
      return t(locale, "kindStepClaimRequested");
    case "comment_added":
      return t(locale, "kindCommentAdded");
    case "member_joined":
      return t(locale, "kindMemberJoined");
    default:
      return kind;
  }
}
